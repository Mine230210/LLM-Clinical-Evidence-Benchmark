"""Prepare Figure 2 data from the three analysis output directories.

No manuscript result is stored in this module. All values are read from CSV
files generated by the public analysis scripts.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd


MODELS = ["ChatGPT", "DeepSeek", "Gemini"]
COLORS = {"ChatGPT": "#0072B2", "DeepSeek": "#009E73", "Gemini": "#D89000"}


def read_result(directory: Path, filename: str, *, required: bool = True) -> pd.DataFrame | None:
    path = directory / filename
    if not path.exists():
        if required:
            raise FileNotFoundError(f"Missing analysis output: {path}")
        return None
    return pd.read_csv(path)


def ordered(frame: pd.DataFrame) -> pd.DataFrame:
    out = frame.copy()
    out["Model"] = pd.Categorical(out["Model"], categories=MODELS, ordered=True)
    out = out.sort_values("Model").reset_index(drop=True)
    if list(out["Model"].astype(str)) != MODELS:
        raise ValueError("Expected exactly one row for each of ChatGPT, DeepSeek, and Gemini")
    return out


def one_row(frame: pd.DataFrame, mask: pd.Series, description: str) -> pd.Series:
    selected = frame.loc[mask]
    if len(selected) != 1:
        raise ValueError(f"Expected one {description} row; found {len(selected)}")
    return selected.iloc[0]


def performance_frame(
    frame: pd.DataFrame,
    mask: pd.Series,
    estimate: str,
    low: str,
    high: str,
    *,
    percent_scale: bool = False,
) -> pd.DataFrame:
    selected = frame.loc[mask, ["Model", estimate, low, high]].rename(
        columns={estimate: "Estimate", low: "CI95_Lower", high: "CI95_Upper"}
    )
    selected = ordered(selected)
    if percent_scale:
        selected[["Estimate", "CI95_Lower", "CI95_Upper"]] /= 100.0
    return selected


def reliability_rows_from_task1(frame: pd.DataFrame) -> list[dict]:
    rows: list[dict] = []
    for model in MODELS:
        row = one_row(
            frame,
            (frame["Model"] == model) & (frame["Group"] == "Overall") & (frame["Outcome"] == "Joint Success"),
            f"Task 1 reliability for {model}",
        )
        rows.extend([
            {
                "Outcome": "Task 1 · Joint-success status",
                "Model": model,
                "Metric": "Observed agreement",
                "Estimate": 100 * float(row["Observed_Agreement"]),
                "CI_Low": 100 * float(row["Agreement_CI_Lower"]),
                "CI_High": 100 * float(row["Agreement_CI_Upper"]),
            },
            {
                "Outcome": "Task 1 · Joint-success status",
                "Model": model,
                "Metric": "Cohen kappa",
                "Estimate": float(row["Cohen_Kappa"]),
                "CI_Low": np.nan,
                "CI_High": np.nan,
            },
        ])
    return rows


def reliability_rows_from_task2(frame: pd.DataFrame) -> list[dict]:
    rows: list[dict] = []
    for model in MODELS:
        for source_metric, figure_metric in [
            ("Observed Agreement", "Observed agreement"),
            ("Unweighted Cohen's kappa", "Cohen kappa"),
        ]:
            row = one_row(
                frame,
                (frame["Model"] == model) & (frame["Group"] == "Overall") & (frame["Metric"] == source_metric),
                f"Task 2 {source_metric} for {model}",
            )
            is_agreement = source_metric == "Observed Agreement"
            scale = 100.0 if is_agreement else 1.0
            rows.append({
                "Outcome": "Task 2 · Controversy classification",
                "Model": model,
                "Metric": figure_metric,
                "Estimate": scale * float(row["Estimate"]),
                "CI_Low": scale * float(row["CI95_Lower"]),
                "CI_High": scale * float(row["CI95_Upper"]),
            })
    return rows


def reliability_rows_from_task3(frame: pd.DataFrame, *, include_reason: bool) -> list[dict]:
    rows: list[dict] = []
    specifications = [
        ("Task 3 · Applicability verdict", "Verdict Observed Agreement", "Observed agreement"),
        ("Task 3 · Applicability verdict", "Verdict Cohen's kappa", "Cohen kappa"),
    ]
    if include_reason:
        specifications.extend([
            ("Task 3 · Reason-quality rating", "Key-reason Observed Agreement", "Observed agreement"),
            ("Task 3 · Reason-quality rating", "Key-reason Cohen's kappa", "Cohen kappa"),
        ])
    for outcome, source_metric, figure_metric in specifications:
        for model in MODELS:
            row = one_row(
                frame,
                (frame["Model"] == model) & (frame["Metric"] == source_metric),
                f"{source_metric} for {model}",
            )
            rows.append({
                "Outcome": outcome,
                "Model": model,
                "Metric": figure_metric,
                "Estimate": float(row["Estimate"]),
                "CI_Low": float(row["CI_Low"]) if pd.notna(row["CI_Low"]) else np.nan,
                "CI_High": float(row["CI_High"]) if pd.notna(row["CI_High"]) else np.nan,
            })
    return rows


def load_analysis_outputs(
    task1_results: Path,
    task2_results: Path,
    task3_results: Path,
) -> tuple[dict[str, pd.DataFrame], list[str]]:
    task1_performance = read_result(task1_results, "performance.csv")
    task1_contrast = read_result(task1_results, "visibility_contrast.csv")
    task1_reliability = read_result(task1_results, "reliability.csv")
    task2_performance = read_result(task2_results, "performance.csv")
    task2_contrast = read_result(task2_results, "overall_high_low.csv")
    task2_reliability = read_result(task2_results, "reliability.csv")
    task3_performance = read_result(task3_results, "performance.csv")
    task3_reliability = read_result(task3_results, "reliability.csv")
    task3_contrast = read_result(task3_results, "overall_comparison.csv", required=False)

    task1 = performance_frame(
        task1_performance,
        task1_performance["Group"].eq("Overall"),
        "JSR",
        "JSR_CI_Lower",
        "JSR_CI_Upper",
    )
    task2 = performance_frame(
        task2_performance,
        task2_performance["Metric"].eq("Overall Accuracy"),
        "Estimate",
        "CI95_Lower",
        "CI95_Upper",
    )
    task3_verdict = performance_frame(
        task3_performance,
        task3_performance["Metric"].eq("Verdict Accuracy"),
        "Estimate_Percent",
        "CI_Low_Percent",
        "CI_High_Percent",
        percent_scale=True,
    )

    missing: list[str] = []
    reason_mask = task3_performance["Metric"].eq("Key-reason Accuracy")
    if int(reason_mask.sum()) == 3:
        task3_reason = performance_frame(
            task3_performance,
            reason_mask,
            "Estimate_Percent",
            "CI_Low_Percent",
            "CI_High_Percent",
            percent_scale=True,
        )
    else:
        task3_reason = pd.DataFrame(columns=["Model", "Estimate", "CI95_Lower", "CI95_Upper"])
        missing.append("Task 3 key-reason accuracy")

    contrast_rows: list[dict] = []
    row = one_row(task1_contrast, task1_contrast["Model"].eq("Overall (equal models)"), "Task 1 pooled contrast")
    contrast_rows.append({
        "Task": "Task 1",
        "Difference_pp": float(row["Difference_pp"]),
        "CI95_Lower_pp": float(row["CI95_Lower_pp"]),
        "CI95_Upper_pp": float(row["CI95_Upper_pp"]),
        "Raw_P": float(row["Raw_P"]),
    })
    row = one_row(task2_contrast, task2_contrast["Gold_Group_or_Contrast"].eq("LOW minus HIGH"), "Task 2 pooled contrast")
    contrast_rows.append({
        "Task": "Task 2",
        "Difference_pp": float(row["Difference_pp"]),
        "CI95_Lower_pp": float(row["Difference_CI95_Lower_pp"]),
        "CI95_Upper_pp": float(row["Difference_CI95_Upper_pp"]),
        "Raw_P": float(row["Raw_Two_Sided_P"]),
    })
    if task3_contrast is not None:
        row = one_row(
            task3_contrast,
            task3_contrast["Metric"].eq("Verdict minus Key-reason Accuracy"),
            "Task 3 pooled contrast",
        )
        contrast_rows.append({
            "Task": "Task 3",
            "Difference_pp": float(row["Estimate_or_Difference_pp"]),
            "CI95_Lower_pp": float(row["CI_Low"]),
            "CI95_Upper_pp": float(row["CI_High"]),
            "Raw_P": float(row["P_Value_Two_Sided"]),
        })
    else:
        missing.append("Task 3 verdict versus key-reason exploratory comparison")

    task3_reason_metrics = {
        "Key-reason Observed Agreement",
        "Key-reason Cohen's kappa",
    }
    has_reason_reliability = task3_reason_metrics.issubset(set(task3_reliability["Metric"]))
    if not has_reason_reliability:
        missing.append("Task 3 key-reason repeated-response reliability")

    reliability_rows = (
        reliability_rows_from_task1(task1_reliability)
        + reliability_rows_from_task2(task2_reliability)
        + reliability_rows_from_task3(task3_reliability, include_reason=has_reason_reliability)
    )
    data = {
        "task1": task1,
        "task2": task2,
        "task3_verdict": task3_verdict,
        "task3_reason": task3_reason,
        "contrasts": pd.DataFrame(contrast_rows),
        "reliability": pd.DataFrame(reliability_rows),
    }
    validate_data(data, full=not missing)
    return data, missing


def validate_data(data: dict[str, pd.DataFrame], *, full: bool) -> None:
    for key in ["task1", "task2", "task3_verdict"]:
        frame = data[key]
        if list(frame["Model"].astype(str)) != MODELS:
            raise ValueError(f"Unexpected model coverage in {key}")
        values = frame[["Estimate", "CI95_Lower", "CI95_Upper"]].astype(float)
        if not np.isfinite(values.to_numpy()).all():
            raise ValueError(f"Missing or non-finite performance result in {key}")
        if not ((values["CI95_Lower"] <= values["Estimate"]) & (values["Estimate"] <= values["CI95_Upper"])).all():
            raise ValueError(f"Invalid confidence interval in {key}")
    if full:
        if list(data["task3_reason"]["Model"].astype(str)) != MODELS:
            raise ValueError("Full Figure 2 requires all three Task 3 key-reason rows")
        if set(data["contrasts"]["Task"]) != {"Task 1", "Task 2", "Task 3"}:
            raise ValueError("Full Figure 2 requires all three pooled contrasts")
        if len(data["reliability"]) != 24:
            raise ValueError("Full Figure 2 requires 24 reliability rows")
    elif len(data["reliability"]) != 18:
        raise ValueError("Public Figure 2 data should contain 18 publicly reproducible reliability rows")


def percent_frame(frame: pd.DataFrame) -> pd.DataFrame:
    out = frame.copy()
    out["Value"] = 100 * out["Estimate"]
    out["Low"] = 100 * out["CI95_Lower"]
    out["High"] = 100 * out["CI95_Upper"]
    return out


def export_source_data(data: dict[str, pd.DataFrame], output_dir: Path, missing: list[str]) -> None:
    performance_rows: list[dict] = []
    specifications = [
        ("a", "Joint Q1–Q2 success", data["task1"]),
        ("b", "Classification accuracy", data["task2"]),
        ("c", "Applicability verdict accuracy", data["task3_verdict"]),
    ]
    if not data["task3_reason"].empty:
        specifications.append(("c", "Key-reason accuracy", data["task3_reason"]))
    for panel, metric, frame in specifications:
        for row in frame.to_dict("records"):
            performance_rows.append({"Panel": panel, "Metric": metric, **row})
    pd.DataFrame(performance_rows).to_csv(output_dir / "Figure2_Source_Performance.csv", index=False)
    data["contrasts"].to_csv(output_dir / "Figure2_Source_Exploratory_Contrasts.csv", index=False)
    data["reliability"].to_csv(output_dir / "Figure2_Source_Reliability.csv", index=False)
    status = {
        "complete_figure_available": not missing,
        "missing_restricted_components": missing,
        "source": "analysis outputs generated from Figshare Gold and Responses CSV files",
    }
    (output_dir / "Figure2_Data_Availability.json").write_text(
        json.dumps(status, indent=2, ensure_ascii=False), encoding="utf-8"
    )
